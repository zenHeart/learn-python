text = "hello world"

print("str:", text)
# 大写首字母
print("str.title():", text.title())
# 大写所有字符
print("str.upper():", text.upper())
# 小写所有字符
print("str.lower():", text.lower())
# 拼接字符
print("'a''b':", 'a''b')
print("'1' + text:", '1' + text)
# 删除前后的空白
print("str.rstrip():", ('\t'+text+'\t').rstrip())
